namespace ODCC.Domain.Modules.Analytics.Enums;

/// <summary>
/// نوع شاخص تحلیلی. تعیین‌کننده‌ی نحوه‌ی محاسبه و مقایسه با بنچمارک است.
/// مقادیر به‌صورت <c>int</c> ذخیره می‌شوند تا افزودن شاخص جدید در آینده
/// فقط افزودن یک عضو اینجا باشد و ردیف‌های موجود نامعتبر نشوند.
/// </summary>
public enum MetricType
{
    /// <summary>شاخص خالص ترویج‌کنندگان (NPS) — پرسشنامه‌ی امتیازدهی ۱ تا ۱۰.</summary>
    Nps = 1,

    /// <summary>رضایت مشتری (CSAT) — درصد پاسخ‌های ۴ و ۵ در طیف ۱ تا ۵.</summary>
    Csat = 2,

    /// <summary>تلاش مشتری (CES) — درصد پاسخ‌های کم‌تلاش (۵ به بالا) در طیف ۱ تا ۷.</summary>
    Ces = 3,

    /// <summary>نرخ تکمیل — نسبت نشست‌های ارسال‌شده به کل نشست‌های شروع‌شده.</summary>
    CompletionRate = 4,

    /// <summary>نرخ پاسخ‌گویی — نسبت دعوت‌نامه‌های پاسخ‌داده به کل توزیع‌های یک کمپین.</summary>
    ResponseRate = 5,

    /// <summary>میانگین امتیاز — میانگین همه‌ی پاسخ‌های امتیازدهی.</summary>
    AverageRating = 6
}
